def get_current_language() -> str:
    """Return the active language code with English as the safe default."""
    lang = st.session_state.get("lang", "en")
    return lang if lang in TRANSLATIONS else "en"


def t(key: str, **kwargs: object) -> str:
    """Translate a UI key using session language, falling back to English."""
    lang = get_current_language()
    text = TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS["en"].get(key) or key

    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text

    return text


def render_language_selector(key: str = "language_selector") -> None:
    """Render the shared language selector and persist the selected language code."""
    current_label = LANGUAGE_LABEL_BY_CODE.get(get_current_language(), "English")
    selected_label = st.selectbox(
        t("language"),
        LANGUAGE_OPTIONS,
        index=LANGUAGE_OPTIONS.index(current_label),
        key=key,
    )
    st.session_state.lang = LANGUAGE_CODE_BY_LABEL[selected_label]
